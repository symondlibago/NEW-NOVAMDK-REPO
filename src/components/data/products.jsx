/**
 * The prescription catalog is entirely compounded. A brand-name (FDA-approved)
 * product opts out with `fdaApproved: true`, and a non-prescription retail item
 * opts out with `otc: true`. Drives the "Compounded" label and disclaimer.
 */
export const isCompounded = (product) => !product?.fdaApproved && !product?.otc;

/** Non-prescription retail products — no Rx label, no intake handoff. */
export const isOtc = (product) => !!product?.otc;

/**
 * Cross-listing (2026-09-08). A treatment that fits two goals is shown on both
 * shelves from ONE record — never a second copy of the product, which would mean
 * two /product/… URLs for the same thing, two pages for Google to choose
 * between, and two places to keep the clinical copy in step.
 *
 * `categorySlug` stays the single canonical home: it drives the breadcrumb, the
 * SEO category, the dose ladder and the "More in …" rail, so a cross-listed
 * product still has exactly one place it belongs to. `alsoIn` is additive and
 * only widens which category listings pick it up.
 */
export const categoriesOf = (product) =>
  [product?.categorySlug, ...(product?.alsoIn || [])].filter(Boolean);

/** True when `slug` is the product's home category or one it is cross-listed into. */
export const inCategory = (product, slug) => categoriesOf(product).includes(slug);

